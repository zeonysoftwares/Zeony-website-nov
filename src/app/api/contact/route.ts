import { NextResponse } from 'next/server';
import nodemailer from 'nodemailer';
import { Resend } from 'resend';
import { supabase } from '@/lib/supabase';

export const dynamic = 'force-dynamic';

export async function POST(req: Request) {
  try {
    const data = await req.json();
    const { name, email, phone, course, message, source, extraFields } = data;

    // 1. Always attempt to store the inquiry in Supabase table "contact_inquiries"
    try {
      await supabase.from('contact_inquiries').insert([
        {
          name: name || 'Anonymous',
          email: email || 'N/A',
          phone: phone || null,
          course_or_service: course || null,
          message: message || '',
          source: source || 'Website Contact Form',
          extra_fields: extraFields || {},
          status: 'new',
        },
      ]);
    } catch (dbErr) {
      console.warn('Could not insert inquiry into database:', dbErr);
    }

    let subject = `New Inquiry from ${name || 'Website Visitor'}`;
    if (source) {
      subject = `[${source}] New Submission: ${course || name || 'Applicant'}`;
    }

    let htmlBody = `
      <div style="font-family: Arial, sans-serif; max-width: 650px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 12px; background-color: #ffffff;">
        <div style="background: linear-gradient(135deg, #0c194b, #1e3a8a); padding: 18px 24px; border-radius: 8px; margin-bottom: 20px;">
          <h2 style="color: #ffffff; margin: 0; font-size: 20px;">Zeony Technologies Notification</h2>
          <p style="color: #93c5fd; margin: 4px 0 0 0; font-size: 13px;">${source || 'Website Submission'}</p>
        </div>
        <p style="font-size: 14px; color: #334155;"><strong>Applicant / Contact Name:</strong> ${name || 'N/A'}</p>
        <p style="font-size: 14px; color: #334155;"><strong>Email:</strong> <a href="mailto:${email}" style="color: #2563eb;">${email || 'N/A'}</a></p>
        <p style="font-size: 14px; color: #334155;"><strong>Phone:</strong> ${phone || 'N/A'}</p>
    `;

    if (course) {
      htmlBody += `<p style="font-size: 14px; color: #334155;"><strong>Program / Domain:</strong> <span style="background-color: #dbeafe; color: #1e40af; padding: 3px 8px; border-radius: 6px; font-weight: 600;">${course}</span></p>`;
    }

    if (message) {
      htmlBody += `<p style="font-size: 14px; color: #334155;"><strong>Message / Notes:</strong><br/>${message.replace(/\n/g, '<br/>')}</p>`;
    }

    if (extraFields && typeof extraFields === 'object') {
      htmlBody += '<h3 style="margin-top: 24px; color: #0f172a; font-size: 16px; border-bottom: 2px solid #e2e8f0; padding-bottom: 6px;">Application Details</h3>';
      htmlBody += '<table style="width:100%; border-collapse: collapse; text-align: left; margin-top: 10px;">';
      for (const [key, value] of Object.entries(extraFields)) {
        htmlBody += `
          <tr>
            <td style="padding: 10px; border: 1px solid #e2e8f0; font-weight: 600; width: 40%; background-color: #f8fafc; color: #475569; font-size: 13px;">${key}</td>
            <td style="padding: 10px; border: 1px solid #e2e8f0; color: #1e293b; font-size: 13px;">${value || 'N/A'}</td>
          </tr>
        `;
      }
      htmlBody += '</table>';
    }

    htmlBody += `
        <hr style="border: none; border-top: 1px solid #e2e8f0; margin: 24px 0 16px 0;" />
        <p style="font-size: 11px; color: #94a3b8; margin: 0;">Automated notification generated by Zeony Technologies System</p>
      </div>
    `;

    // 2. PRIMARY: Send email via verified Gmail SMTP
    const smtpUser = process.env.SMTP_EMAIL;
    const smtpPass = process.env.SMTP_PASSWORD;
    let emailSent = false;

    if (smtpUser && smtpPass) {
      try {
        const transporter = nodemailer.createTransport({
          service: 'gmail',
          auth: {
            user: smtpUser.trim(),
            pass: smtpPass.trim(),
          },
        });

        await transporter.sendMail({
          from: `"Zeony Technologies" <${smtpUser.trim()}>`,
          to: smtpUser.trim(),
          replyTo: email || smtpUser.trim(),
          subject: subject,
          html: htmlBody,
        });
        emailSent = true;
      } catch (smtpErr) {
        console.warn('Gmail SMTP send warning:', smtpErr);
      }
    }

    // 3. SECONDARY / FALLBACK: Send via Resend if configured
    if (!emailSent) {
      const resendApiKey = process.env.RESEND_API_KEY;
      if (resendApiKey && smtpUser) {
        try {
          const resend = new Resend(resendApiKey);
          await resend.emails.send({
            from: 'Zeony Technologies <notifications@zeonytechnologies.com>',
            to: smtpUser,
            replyTo: email,
            subject: subject,
            html: htmlBody,
          });
          emailSent = true;
        } catch (resendErr) {
          console.warn('Resend send warning:', resendErr);
        }
      }
    }

    return NextResponse.json({
      success: true,
      message: 'Inquiry received successfully! Our team will contact you shortly.',
      emailSent,
    });
  } catch (error: unknown) {
    console.error('Error in contact route:', error);
    return NextResponse.json(
      { success: false, message: 'An unexpected error occurred.', error: error instanceof Error ? error.message : 'Unknown error' },
      { status: 500 }
    );
  }
}
